def mmss(seconds) -> str:
    s = int(round(seconds))
    return f"{s // 60}:{s % 60:02d}"


def split_header(header: str):
    header = CLOCK_RE.sub("", header)
    cp = ""
    m = re.search(r"·\s*(checkpoint\s+[①②③\d]+)", header)
    if m:
        cp = m.group(1)
    return CHECKPOINT_RE.sub("", header).strip(" ·—"), cp


def timings(sections):
    out, running = {}, 0.0
    for num_str, _header, body in sections:
        secs = len(clean_spoken(body).split()) * 60 / WPM
        running += secs
        out[num_str] = f"{mmss(secs)} → {mmss(running)}"
    return out


def strip_markdown_comments(text: str) -> str:
    text = re.sub(r"<!--[\s\S]*?-->", "", text)
    text = re.sub(r"^\s*\[//\]:\s*#.*$", "", text, flags=re.M)
    text = re.sub(r"^\s*//.*$", "", text, flags=re.M)
    return text


def format_typst_text(text: str) -> str:
    text = strip_markdown_comments(text)
    lines = []
    for para in text.strip().split("\n\n"):
        para = para.strip().replace("\n", " ")
        if not para:
            continue
        if para.startswith("*(") and para.endswith(")*"):
            inner = para[2:-2].strip()
            lines.append(f'#text(fill: rgb("#64748B"), style: "italic")[({inner})]')
        else:
            lines.append(para)
    return "\n\n".join(lines)


