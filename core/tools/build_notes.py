def generate_pdfpc(sections, dst_path: pathlib.Path, duration_mins: int):
    pages = []
    clock = timings(sections)
    for num_str, header, body in sections:
        idx = int(num_str) - 1
        label = str(int(num_str))
        title_str, _cp = split_header(header)
        timing_part = clock[num_str]
        note_text = f"### Slide {num_str} · {title_str} (⏱ {timing_part})\n\n{body.strip()}"
        pages.append({
            "idx": idx,
            "label": label,
            "overlay": 0,
            "forcedOverlay": False,
            "hidden": False,
            "note": note_text,
        })
    pdfpc_data = {
        "pdfpcFormat": 2,
        "disableMarkdown": False,
        "duration": duration_mins,
        "lastSlide": len(sections),
        "pages": pages,
    }
    dst_path.write_text(json.dumps(pdfpc_data, indent=2, ensure_ascii=False) + "\n")
    print(f"==> {dst_path.name} generated")


def compile_typst(src: pathlib.Path, dst: pathlib.Path):
    typst_bin = os.environ.get("TYPST", "typst")
    res = subprocess.run([typst_bin, "compile", "--root", str(ROOT), str(src), str(dst)], capture_output=True, text=True)
    if res.returncode != 0:
        print(f"FAIL: compiling {src.name}: {res.stderr}", file=sys.stderr)
        sys.exit(res.returncode)
    print(f"==> {dst.name} generated")


def main():
    cfg = load_config()
    name = cfg["deck"]["name"]
    out_dir_rel = cfg["build"].get("out_dir", "render")
    render = ROOT / out_dir_rel
    script_md = ROOT / cfg.get("script", {}).get("path", "slides/SCRIPT.md")
    duration_mins = int(cfg.get("script", {}).get("duration_minutes", 12))

    handout_rel = f"{out_dir_rel}/{name}-talk-handout.pdf"
    if not (ROOT / handout_rel).exists():
        print(f"Error: {handout_rel} not found — compile deck first", file=sys.stderr)
        sys.exit(1)

    content = strip_markdown_comments(script_md.read_text())
    sections = re.findall(r"^## (?:Slide )?(\d\d) · (.*?)\n(.*?)(?=\n## |\n---|\Z)", content, re.M | re.S)

    notes_typ = ROOT / "core" / "notes.typ"
    script_typ = ROOT / "core" / "script.typ"
    print("==> building notes and script PDFs from SCRIPT.md")
    generate_notes_typ(cfg, sections, handout_rel, notes_typ)
    compile_typst(notes_typ, render / f"{name}-talk-notes.pdf")

    generate_script_typ(cfg, content, sections, script_typ)
    compile_typst(script_typ, render / f"{name}-script.pdf")

    generate_pdfpc(sections, render / f"{name}-talk.pdfpc", duration_mins)
    generate_pdfpc(sections, render / f"{name}-talk-handout.pdfpc", duration_mins)


if __name__ == "__main__":
    main()
